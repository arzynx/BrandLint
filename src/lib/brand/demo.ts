type RuleInput = Omit<Rule, "status" | "source" | "owner">;

function withMeta(rules: RuleInput[]): Rule[] {
  return rules.map((r) => ({ status: "approved", ...DOCS[r.section.replace("§", "").split(".")[0]], ...r }));
}

